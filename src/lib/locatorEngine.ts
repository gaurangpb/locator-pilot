const FORM_CONTROL_TAGS = new Set(["input", "textarea", "select"]);
const CONTENT_TAGS = new Set([
  "a",
  "button",
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "label",
  "li",
  "option",
  "span",
  "p",
  "summary",
]);

const MAX_CANDIDATES = 3;
const MAX_TEXT_LENGTH = 80;

function ownText(el: Element): string {
  return (el.textContent || "").replace(/\s+/g, " ").trim();
}

function isAutoGeneratedToken(token: string): boolean {
  return /(?:^|-|_)[a-f0-9]{5,}$/i.test(token) || /^(css|sc|jss|emotion|styled)-[a-z0-9]{4,}$/i.test(token);
}

const STATE_CLASS_PREFIX_RE = /^(is|has|was|will)-/i;
const FRAMEWORK_MARKER_RE = /^(hydrated|ng-|v-|data-v-)/i;
const STATE_WORDS = new Set([
  "active", "selected", "checked", "disabled", "open", "closed", "expanded",
  "collapsed", "hidden", "visible", "current", "focused", "hover", "hovered",
  "pressed", "invalid", "valid", "dirty", "pristine", "touched", "untouched",
  "loading", "error", "success", "highlighted",
]);

/**
 * True for a class that encodes transient state (`sdps-card--selected`, `is-open`)
 * or a framework/hydration marker (`hydrated`, `ng-star-inserted`) rather than a
 * stable structural/styling hook — docs/LOCATOR_STRATEGY.md §2.7. These flip or
 * vanish at runtime with no markup change at all (e.g. a card's `--selected`
 * modifier disappears the moment it's deselected), so a CSS selector built from one
 * can go stale without the page changing.
 */
function isTransientClassToken(token: string): boolean {
  if (FRAMEWORK_MARKER_RE.test(token)) return true;
  if (STATE_CLASS_PREFIX_RE.test(token)) return true;
  const lower = token.toLowerCase();
  if (STATE_WORDS.has(lower)) return true;
  const bemModifier = /--([a-z0-9]+)$/.exec(lower);
  return bemModifier !== null && STATE_WORDS.has(bemModifier[1]!);
}

/** Escapes a string for use inside a double-quoted CSS attribute-selector value — distinct
 * from cssEscape (which escapes CSS *identifiers* like tag/class names): inside quotes,
 * spaces and punctuation are fine as-is, and only backslashes/quotes need escaping. */
function cssStringEscape(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const STABLE_CSS_ATTRIBUTES = ["name", "type", "value", "href", "alt", "title"];

/**
 * A short, curated list of attributes that are typically stable across re-renders
 * (unlike auto-generated ids/classes or transient state classes) and often carry
 * real semantic meaning — e.g. a radio group's `value`. Tried ahead of classes, per
 * docs/LOCATOR_STRATEGY.md §2.7.
 */
function findStableAttribute(el: Element): { name: string; value: string } | null {
  for (const name of STABLE_CSS_ATTRIBUTES) {
    const value = el.getAttribute(name);
    if (value && value.trim() && !isAutoGeneratedToken(value)) {
      return { name, value };
    }
  }
  return null;
}

function findAssociatedLabelText(el: Element, doc: Document): string | null {
  const id = el.getAttribute("id");
  if (id) {
    const root = el.getRootNode() as Document | ShadowRoot;
    const label = root.querySelector(`label[for="${cssEscape(id)}"]`);
    if (label) {
      const text = ownText(label);
      if (text) return text;
    }
  }
  const wrapping = el.closest("label");
  if (wrapping) {
    const text = ownText(wrapping);
    if (text) return text;
  }
  return null;
}

/**
 * Builds a short-as-possible CSS selector, preferring a plain id, falling back to a tag+nth-of-type path.
 * Uniqueness is probed with deepQuerySelectorAll — the same shadow-piercing search the matcher
 * (and Playwright's CSS engine) uses — so a selector for an element inside a shadow root is
 * shortened against what's actually on the page, not just the light DOM it can't see.
 */
function buildCssSelector(el: Element, doc: Document): string {
  const isUnique = (selector: string): boolean => deepQuerySelectorAll(doc, selector).length === 1;
  if (el.id) {
    const idSelector = `#${cssEscape(el.id)}`;
    if (isUnique(idSelector)) return idSelector;
  }

  const segments: string[] = [];
  let node: Element | null = el;

  while (node && node.nodeType === 1) {
    if (node.id) {
      segments.unshift(`#${cssEscape(node.id)}`);
      break;
    }

    const parent: Element | null = node.parentElement;
    let segment = node.tagName.toLowerCase();
    const stableAttr = findStableAttribute(node);
    if (stableAttr) {
      // A distinguishing attribute is already specific enough on its own — skip
      // nth-of-type here so we don't needlessly couple the selector to sibling
      // order (and get flagged fragile for it) on top of an already-good match.
      segment += `[${stableAttr.name}="${cssStringEscape(stableAttr.value)}"]`;
    } else {
      const stableClasses = Array.from(node.classList).filter(
        (c) => !isAutoGeneratedToken(c) && !isTransientClassToken(c),
      );
      if (stableClasses.length > 0) {
        segment += stableClasses.map((c) => `.${cssEscape(c)}`).join("");
      }

      if (parent) {
        const sameTagSiblings = Array.from(parent.children).filter(
          (c) => c.tagName === node!.tagName,
        );
        if (sameTagSiblings.length > 1) {
          segment += `:nth-of-type(${sameTagSiblings.indexOf(node) + 1})`;
        }
      }
    }

    segments.unshift(segment);
    node = parent;
  }

  // Try the shortest trailing slice of the path that still uniquely resolves.
  for (let start = segments.length - 1; start >= 0; start--) {
    const candidate = segments.slice(start).join(" > ");
    // deepQuerySelectorAll already swallows a malformed intermediate selector.
    if (isUnique(candidate)) return candidate;
  }

  return segments.join(" > ");
}

function buildXPath(el: Element): string {
  const segments: string[] = [];
  let node: Element | null = el;

  while (node && node.nodeType === 1) {
    const tag = node.tagName.toLowerCase();
    const parent: Element | null = node.parentElement;
    if (!parent) {
      segments.unshift(tag);
      break;
    }
    const sameTagSiblings = Array.from(parent.children).filter((c) => c.tagName === node!.tagName);
    const index = sameTagSiblings.indexOf(node) + 1;
    segments.unshift(sameTagSiblings.length > 1 ? `${tag}[${index}]` : tag);
    node = parent;
  }

  return `//${segments.join("/")}`;
}

/**
 * Strategy order here follows docs/LOCATOR_STRATEGY.md §2: role → label →
 * placeholder → altText/title → text → testId → css → xpath. That doc is the source
 * of truth for *why* — keep it in sync with any change here.
 */
function buildSpecs(el: Element, doc: Document, options: EngineOptions): LocatorSpec[] {
  const specs: LocatorSpec[] = [];
  const tag = el.tagName.toLowerCase();
  const role = getImplicitRole(el);

  if (role) {
    const name = getAccessibleName(el, doc);
    if (name) {
      specs.push({ strategy: "role", role, name, exact: false });
    } else {
      specs.push({ strategy: "role", role, exact: false });
    }
  }

  if (FORM_CONTROL_TAGS.has(tag)) {
    const labelText = findAssociatedLabelText(el, doc);
    if (labelText) specs.push({ strategy: "label", text: labelText, exact: false });

    const placeholder = el.getAttribute("placeholder");
    if (placeholder?.trim()) {
      specs.push({ strategy: "placeholder", text: placeholder.trim(), exact: false });
    }
  }

  // docs/LOCATOR_STRATEGY.md §2.4 — images/icons without visible text. `alt` only
  // applies to <img>; `title` is worth a candidate on any element, but only when
  // there's no visible text already covering the same ground.
  if (tag === "img") {
    const alt = el.getAttribute("alt");
    if (alt !== null && alt.trim()) {
      specs.push({ strategy: "altText", text: alt.trim(), exact: false });
    }
  }

  const titleAttr = el.getAttribute("title");
  if (titleAttr?.trim() && !ownText(el)) {
    specs.push({ strategy: "title", text: titleAttr.trim(), exact: false });
  }

  if (CONTENT_TAGS.has(tag)) {
    const text = ownText(el);
    if (text && text.length <= MAX_TEXT_LENGTH) {
      specs.push({ strategy: "text", text, exact: false });
    }
  }

  const testIdValue = el.getAttribute(options.testIdAttribute);
  if (testIdValue) {
    specs.push({ strategy: "testId", attribute: options.testIdAttribute, value: testIdValue });
  }

  specs.push({ strategy: "css", selector: buildCssSelector(el, doc) });
  specs.push({ strategy: "xpath", expression: buildXPath(el) });

  return specs;
}

const MAX_RESOLUTION_DEPTH = 3;

// Roles worth resolving *to* — actionable controls, not structural/landmark roles
// (heading, img, list, navigation, ...) that happen to have a computable name but
// aren't a better locator target than the element the user actually picked.
const INTERACTIVE_ROLES = new Set([
  "button",
  "link",
  "checkbox",
  "radio",
  "switch",
  "textbox",
  "combobox",
  "listbox",
  "option",
  "menuitem",
  "menuitemcheckbox",
  "menuitemradio",
  "tab",
  "slider",
  "spinbutton",
  "searchbox",
]);

const SR_ONLY_CLASS_RE = /(?:^|-)sr-only$/i;
const VISUALLY_HIDDEN_CLASS_RE = /^visually-?hidden$/i;
const SCREEN_READER_CLASS_RE = /^screen-?reader(?:-?text)?$/i;

/**
 * True for the classic "screen-reader-only" utility-class pattern (Bootstrap's and
 * Tailwind's `.sr-only`, a design system's own e.g. `.sdps-sr-only`, WordPress's
 * `.screen-reader-text`, `.visually-hidden`, ...) — used to keep a native form
 * control in the accessibility tree while hiding it from sighted/mouse users, almost
 * always paired with a wrapping `<label>` that IS the real, visible click target.
 * Resolving to such an element (docs/LOCATOR_STRATEGY.md §1) technically produces a
 * valid, unique role/name match, but its on-page position is wherever the hidden
 * input happens to render — usually nowhere near anything the element visually
 * represents — so the highlight (and the "click this" intent) is confusing at best.
 */
function isScreenReaderOnly(el: Element): boolean {
  return Array.from(el.classList).some(
    (c) => SR_ONLY_CLASS_RE.test(c) || VISUALLY_HIDDEN_CLASS_RE.test(c) || SCREEN_READER_CLASS_RE.test(c),
  );
}

function isInteractiveResolutionTarget(el: Element, doc: Document): boolean {
  const role = getImplicitRole(el);
  if (!role || !INTERACTIVE_ROLES.has(role)) return false;
  if (!isExposedToAccessibilityTree(el)) return false;
  if (isScreenReaderOnly(el)) return false;
  return getAccessibleName(el, doc).length > 0;
}

function hasDirectSpec(specs: LocatorSpec[]): boolean {
  return specs.some((spec) => spec.strategy !== "css" && spec.strategy !== "xpath");
}

function findInteractiveAncestor(el: Element, doc: Document): Element | null {
  let node: Element | null = el.parentElement;
  let depth = 0;
  while (node && depth < MAX_RESOLUTION_DEPTH) {
    if (isInteractiveResolutionTarget(node, doc)) return node;
    node = node.parentElement;
    depth += 1;
  }
  return null;
}

function collectInteractiveDescendants(el: Element, doc: Document): Element[] {
  const found: Element[] = [];
  const walk = (node: Element, depth: number): void => {
    if (depth > MAX_RESOLUTION_DEPTH) return;
    for (const child of Array.from(node.children)) {
      if (isInteractiveResolutionTarget(child, doc)) found.push(child);
      else walk(child, depth + 1);
    }
  };
  walk(el, 0);
  return found;
}

interface ResolvedTarget {
  element: Element;
  resolvedVia: ResolutionKind | null;
}

/**
 * Implements docs/LOCATOR_STRATEGY.md §1: when `el` itself yields no role/label/
 * placeholder/text/testId spec of its own — common for custom-element wrappers
 * around a real control, e.g. a `<sdps-card>` wrapping a labelled radio `<input>` —
 * look for a uniquely-identifiable interactive ancestor, then descendant, to build
 * specs from instead. Promotes only on an unambiguous single match; zero or
 * multiple candidates always fall back to `el` itself, even if that means a worse
 * (css/xpath-only) locator — a silently wrong guess is worse than an honestly
 * fragile one.
 */
function resolveTargetElement(el: Element, doc: Document, directSpecs: LocatorSpec[]): ResolvedTarget {
  if (hasDirectSpec(directSpecs)) return { element: el, resolvedVia: null };

  const ancestor = findInteractiveAncestor(el, doc);
  if (ancestor) return { element: ancestor, resolvedVia: "ancestor" };

  const descendants = collectInteractiveDescendants(el, doc);
  if (descendants.length === 1) return { element: descendants[0]!, resolvedVia: "descendant" };

  return { element: el, resolvedVia: null };
}

function parentOrHost(node: Element): Element | null {
  if (node.parentElement) return node.parentElement;
  const root = node.getRootNode();
  return root instanceof ShadowRoot ? root.host : null;
}

const MAX_CHAIN_DEPTH = 6;
const MAX_SCOPE_TEXT_LENGTH = 50;
const CONTAINER_ROLES = new Set([
  "row",
  "listitem",
  "article",
  "region",
  "dialog",
  "form",
  "navigation",
  "group",
  "tabpanel",
  "complementary",
  "main",
  "banner",
  "contentinfo",
]);
const TEXT_FILTER_CONTAINER_ROLES = new Set(["row", "listitem", "article"]);

function explicitAriaName(el: Element, doc: Document): string | null {
  const labelledBy = el.getAttribute("aria-labelledby");
  if (labelledBy) {
    const text = labelledBy
      .split(/\s+/)
      .map((id) => doc.getElementById(id)?.textContent ?? "")
      .map((t) => t.replace(/\s+/g, " ").trim())
      .filter(Boolean)
      .join(" ");
    if (text) return text;
  }
  const ariaLabel = el.getAttribute("aria-label")?.replace(/\s+/g, " ").trim();
  return ariaLabel || null;
}

/**
 * Picks a short, human-readable text snippet inside `container` (excluding `target`
 * itself) suitable for `.filter({ hasText })` — e.g. the first label cell in a `<tr>`
 * or the leading text of an `<li>`.
 */
function extractDistinguishingText(container: Element, target: Element): string | null {
  const tag = container.tagName.toLowerCase();
  if (tag === "tr") {
    for (const cell of Array.from(container.children)) {
      const cellTag = cell.tagName.toLowerCase();
      if (cellTag !== "td" && cellTag !== "th") continue;
      if (cell === target || cell.contains(target)) continue;
      const text = ownText(cell);
      if (text && text.length <= MAX_SCOPE_TEXT_LENGTH) return text;
    }
    return null;
  }

  for (const child of Array.from(container.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE) {
      const text = (child.textContent || "").replace(/\s+/g, " ").trim();
      if (text && text.length <= MAX_SCOPE_TEXT_LENGTH) return text;
    } else if (child.nodeType === Node.ELEMENT_NODE) {
      const childEl = child as Element;
      if (childEl === target || childEl.contains(target)) continue;
      const childRole = getImplicitRole(childEl);
      if (childRole && INTERACTIVE_ROLES.has(childRole)) continue;
      const text = ownText(childEl);
      if (text && text.length <= MAX_SCOPE_TEXT_LENGTH) return text;
    }
  }
  return null;
}

/**
 * When a semantic spec for `el` matches multiple elements (e.g. a "Delete" button
 * repeated in every table row), walks up ancestors looking for the nearest scoping
 * container (test-id, named landmark/dialog, or row/listitem with distinguishing text)
 * that makes the combined chained locator uniquely resolve to `el`.
 */
function buildChainedSpec(
  el: Element,
  childSpec: LocatorSpec,
  doc: Document,
  options: EngineOptions,
): LocatorSpec | null {
  if (childSpec.strategy === "css" || childSpec.strategy === "xpath" || childSpec.strategy === "chained") {
    return null;
  }

  let ancestor = parentOrHost(el);
  let depth = 0;
  while (ancestor && depth < MAX_CHAIN_DEPTH) {
    const tag = ancestor.tagName.toLowerCase();
    if (tag === "body" || tag === "html") break;

    const scopes: Array<{ parent: LocatorSpec; parentHasText?: string }> = [];

    const testId = ancestor.getAttribute(options.testIdAttribute);
    if (testId) {
      scopes.push({ parent: { strategy: "testId", attribute: options.testIdAttribute, value: testId } });
    }

    const role = getImplicitRole(ancestor);
    if (role && CONTAINER_ROLES.has(role) && isExposedToAccessibilityTree(ancestor)) {
      const ariaName = explicitAriaName(ancestor, doc);
      if (ariaName && ariaName.length <= MAX_SCOPE_TEXT_LENGTH) {
        scopes.push({ parent: { strategy: "role", role, name: ariaName, exact: false } });
      }
      if (TEXT_FILTER_CONTAINER_ROLES.has(role)) {
        const text = extractDistinguishingText(ancestor, el);
        if (text) {
          scopes.push({
            parent: { strategy: "role", role, exact: false },
            parentHasText: text,
          });
        }
      }
    }

    for (const scope of scopes) {
      const chained: LocatorSpec = {
        strategy: "chained",
        parent: scope.parent,
        ...(scope.parentHasText ? { parentHasText: scope.parentHasText } : {}),
        child: childSpec,
      };
      const matches = matchLocator(doc, chained);
      if (matches.length === 1 && matches[0] === el) return chained;
    }

    ancestor = parentOrHost(ancestor);
    depth += 1;
  }

  return null;
}

/** Builds a concise, stable CSS selector for an `<iframe>` element inside its parent document. */
export function buildFrameSelector(frameEl: Element, testIdAttribute: string): string {
  const doc = frameEl.ownerDocument;
  const isUnique = (selector: string): boolean => deepQuerySelectorAll(doc, selector).length === 1;

  const testId = frameEl.getAttribute(testIdAttribute);
  if (testId) {
    const sel = `[${cssEscape(testIdAttribute)}="${cssStringEscape(testId)}"]`;
    if (isUnique(sel)) return sel;
  }

  for (const attr of ["title", "name"]) {
    const val = frameEl.getAttribute(attr);
    if (val?.trim()) {
      const sel = `iframe[${attr}="${cssStringEscape(val.trim())}"]`;
      if (isUnique(sel)) return sel;
    }
  }

  if (frameEl.id) {
    const sel = `#${cssEscape(frameEl.id)}`;
    if (isUnique(sel)) return sel;
  }

  const src = frameEl.getAttribute("src");
  if (src?.trim() && !src.startsWith("data:") && src.length <= 120) {
    const sel = `iframe[src="${cssStringEscape(src.trim())}"]`;
    if (isUnique(sel)) return sel;
  }

  return buildCssSelector(frameEl, doc);
}

function specKey(spec: LocatorSpec): string {
  return JSON.stringify(spec);
}

/** Builds a fresh candidate from a spec — the single place match-derived fields are computed, so a live re-check or an exact-toggle can recompute a candidate without duplicating this logic (and risking it drifting out of sync, as happened with the hasHiddenMatch check). */
function buildCandidate(spec: LocatorSpec, doc: Document, frameSelectors?: string[]): LocatorCandidate {
  const matches = matchLocator(doc, spec);
  const frames = frameSelectors && frameSelectors.length > 0 ? frameSelectors : undefined;
  return {
    spec,
    matchCount: matches.length,
    isUnique: matches.length === 1,
    // CSS-hidden only (display:none/visibility:hidden) — this is what makes an
    // element non-actionable for Playwright regardless of locator strategy.
    // aria-hidden alone does NOT belong here: it's a common, intentional
    // pattern on visible decorative elements, and only affects accessibility-tree
    // based strategies (role/label), which already filter it out themselves.
    hasHiddenMatch: matches.some((match) => !isCssVisible(match)),
    brittleness: assessBrittleness(spec),
    ...(frames ? { frameSelectors: frames } : {}),
    csharp: toCSharp(spec, frames),
    typescript: toTypeScript(spec, frames),
  };
}

/**
 * Fills the panel's `MAX_CANDIDATES` slots per docs/LOCATOR_STRATEGY.md §2
 * ("Filling the panel"): unique candidates first, in precedence order, then
 * non-unique ones (also in precedence order) only for whatever slots are left.
 *
 * When a semantic spec (role/label/placeholder/altText/title/text/testId) is
 * ambiguous (2+ matches), we also try scoping it to an unambiguous ancestor
 * container (chained disambiguation) ahead of CSS/XPath fallbacks.
 */
function buildCandidateList(
  specs: LocatorSpec[],
  target: Element,
  doc: Document,
  options: EngineOptions,
): LocatorCandidate[] {
  const seen = new Set<string>();
  const unique: LocatorCandidate[] = [];
  const nonUnique: LocatorCandidate[] = [];
  const ambiguousSemantic: LocatorSpec[] = [];
  let triedChaining = false;

  const pushSpec = (spec: LocatorSpec): boolean => {
    const key = specKey(spec);
    if (seen.has(key)) return unique.length >= MAX_CANDIDATES;
    seen.add(key);

    const candidate = buildCandidate(spec, doc, options.frameSelectors);
    (candidate.isUnique ? unique : nonUnique).push(candidate);
    if (
      !candidate.isUnique &&
      candidate.matchCount > 1 &&
      spec.strategy !== "css" &&
      spec.strategy !== "xpath" &&
      spec.strategy !== "chained"
    ) {
      ambiguousSemantic.push(spec);
    }
    return unique.length >= MAX_CANDIDATES;
  };

  for (const spec of specs) {
    // Before falling back to CSS/XPath, try disambiguating the highest-precedence
    // ambiguous semantic spec via an enclosing container (row, listitem, region, testId).
    if (!triedChaining && (spec.strategy === "css" || spec.strategy === "xpath") && ambiguousSemantic.length > 0) {
      triedChaining = true;
      for (const childSpec of ambiguousSemantic) {
        const chained = buildChainedSpec(target, childSpec, doc, options);
        if (chained) {
          if (pushSpec(chained)) return unique.slice(0, MAX_CANDIDATES);
          break;
        }
      }
    }

    if (pushSpec(spec)) break;
  }

  return [...unique, ...nonUnique].slice(0, MAX_CANDIDATES);
}

export interface PickResult {
  candidates: LocatorCandidate[];
  /** The element candidates were actually built from — `el` unless resolution (docs/LOCATOR_STRATEGY.md §1) promoted to an ancestor/descendant. */
  target: Element;
  resolvedVia: ResolutionKind | null;
}

/**
 * Resolves the best target element (docs/LOCATOR_STRATEGY.md §1) and generates its
 * ranked candidates. Prefer this over `generateCandidates` wherever the caller can
 * act on `target`/`resolvedVia` — e.g. to highlight the element candidates actually
 * target and tell the user when it differs from the one they picked.
 */
export function pickCandidates(
  el: Element,
  options: EngineOptions,
  doc: Document = el.ownerDocument,
): PickResult {
  const directSpecs = buildSpecs(el, doc, options);
  const { element: target, resolvedVia } = resolveTargetElement(el, doc, directSpecs);
  const specs = resolvedVia ? buildSpecs(target, doc, options) : directSpecs;
  return { candidates: buildCandidateList(specs, target, doc, options), target, resolvedVia };
}

export function generateCandidates(
  el: Element,
  options: EngineOptions,
  doc: Document = el.ownerDocument,
): LocatorCandidate[] {
  return pickCandidates(el, options, doc).candidates;
}

/** Recomputes matchCount/isUnique/hasHiddenMatch (and codegen/brittleness, which are cheap) for a set of previously-generated candidates against the current DOM state — used to keep the panel from going stale on an SPA that re-renders after a pick. */
export function refreshCandidates(candidates: LocatorCandidate[], doc: Document): LocatorCandidate[] {
  return candidates.map((candidate) => buildCandidate(candidate.spec, doc, candidate.frameSelectors));
}

/** Flips the `exact` flag on the candidate at `index` (a no-op if that strategy has no `exact` field) and recomputes it against the current DOM. */
export function withExact(
  candidates: LocatorCandidate[],
  index: number,
  exact: boolean,
  doc: Document,
): LocatorCandidate[] {
  const target = candidates[index];
  if (!target || !("exact" in target.spec)) return candidates;
  const nextSpec = { ...target.spec, exact } as LocatorSpec;
  const next = candidates.slice();
  next[index] = buildCandidate(nextSpec, doc, target.frameSelectors);
  return next;
}
